/**
 * 各歌词来源的标志（单色，跟随文字颜色）：网易云音乐、QQ 音乐、酷狗音乐、AMLL TTML DB 用各自的标志，
 * 站长的自定义 TTML 用音乐文件图标；没有歌词时为引号图标
 */
export function LyricSourceIcon({ source, className }: { source: LyricSource, className?: string }) {
  switch (source) {
    case 'ncm-yrc':
    case 'ncm-lrc':
      return <SiNeteasecloudmusic aria-hidden className={className} />
    case 'qq-qrc':
    case 'qq-lrc':
      return <QqMusicIcon className={className} />
    case 'kugou-krc':
    case 'kugou-lrc':
      return <KugouIcon className={className} />
    case 'ttml-amll':
      return <AmllIcon className={className} />
    case 'ttml-custom':
      return <FileMusicIcon aria-hidden className={className} />
    default:
      return <MessageSquareQuoteIcon aria-hidden className={className} />
  }
}
